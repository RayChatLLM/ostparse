# bytes.translate tables (identity-indexed) ---------------------------------
_PERMUTE_DECODE = MPBB_I
_PERMUTE_ENCODE = MPBB_R


def permute_decode(data: bytes) -> bytes:
    """Decode a buffer encoded with NDB_CRYPT_PERMUTE."""
    return data.translate(_PERMUTE_DECODE)


def permute_encode(data: bytes) -> bytes:
    """Encode a buffer with NDB_CRYPT_PERMUTE."""
    return data.translate(_PERMUTE_ENCODE)


# Cyclic -------------------------------------------------------------------
#
# For a 16-bit running word ``w`` (lo = w & 0xff, hi = w >> 8) each byte is
# mapped as
#
#     b' = I[ S[ R[(b + lo) & 0xff] + hi ] - hi ] - lo        (mod 256)
#
# and ``w`` is incremented after every byte.  The dependency on ``lo`` is a
# pure index rotation on the way in and a value rotation on the way out, so
# the whole transform factors as
#
#     add_ramp  ->  per-run translate with T[hi]  ->  sub_ramp
#
# where T[hi][x] = I[(S[(R[x] + hi) & 0xff] - hi) & 0xff].  ``hi`` only changes
# every 256 bytes, so a 64 KiB block needs at most ~257 ``bytes.translate``
# calls, and the two ramps are done with 16-bit-lane big-integer arithmetic.
# Everything heavy therefore runs in C even though this is pure Python.

_CYCLIC_T = [None] * 256


def _cyclic_hi_table(hi: int) -> bytes:
    t = _CYCLIC_T[hi]
    if t is None:
        R, S, I = MPBB_R, MPBB_S, MPBB_I
        t = bytes(I[(S[(R[x] + hi) & 0xFF] - hi) & 0xFF] for x in range(256))
        _CYCLIC_T[hi] = t
    return t


_RAMP_LANES = 65536 + 256
_POS_BASE = bytearray(2 * _RAMP_LANES)
_POS_BASE[0::2] = bytes((i & 0xFF) for i in range(_RAMP_LANES))
_POS_BASE = bytes(_POS_BASE)
_NEG_BASE = bytearray(2 * _RAMP_LANES)
_NEG_BASE[0::2] = bytes(((-i) & 0xFF) for i in range(_RAMP_LANES))
_NEG_BASE = bytes(_NEG_BASE)


def _ramp_add(data, lo0: int, base: bytes) -> bytes:
    """Return (data[i] + base[lo0 + i]) & 0xff for every i, using 16-bit lanes."""
    n = len(data)
    lanes = bytearray(2 * n)
    lanes[0::2] = data
    v = int.from_bytes(lanes, "little") + int.from_bytes(base[2 * lo0 : 2 * (lo0 + n)], "little")
    v &= int.from_bytes(b"\xff\x00" * n, "little")
    return v.to_bytes(2 * n, "little")[0::2]


def cyclic_crypt(data: bytes, key: int) -> bytes:
    """Encode *or* decode a buffer with NDB_CRYPT_CYCLIC (the cipher is symmetric).

    ``key`` is the low 32 bits of the BID of the block being processed.
    Buffers longer than 64 KiB are processed in 64 KiB pieces with the running
    word carried across pieces, so the result equals a single pass.
    """
    key &= 0xFFFFFFFF
    w = (key ^ (key >> 16)) & 0xFFFF
    n = len(data)
    if n == 0:
        return b""
    if n <= 65536:
        return _cyclic_with_w(data, w)
    return _cyclic_long(data, w)


def _cyclic_long(data: bytes, w: int) -> bytes:
    out = bytearray()
    n = len(data)
    for off in range(0, n, 65536):
        piece = data[off : off + 65536]
        out += _cyclic_with_w(piece, w)
        w = (w + len(piece)) & 0xFFFF
    return bytes(out)


def _cyclic_with_w(data: bytes, w: int) -> bytes:
    n = len(data)
    lo0 = w & 0xFF
    c = _ramp_add(data, lo0, _POS_BASE)
    out = bytearray(n)
    i = 0
    while i < n:
        hi = (w >> 8) & 0xFF
        lo = w & 0xFF
        run = 256 - lo
        if run > n - i:
            run = n - i
        out[i : i + run] = c[i : i + run].translate(_cyclic_hi_table(hi))
        i += run
        w = (w + run) & 0xFFFF
    return _ramp_add(out, lo0, _NEG_BASE)


def cyclic_crypt_reference(data: bytes, key: int) -> bytes:
    """Straightforward per-byte transcription of [MS-PST] 5.2 (used by tests)."""
    key &= 0xFFFFFFFF
    w = (key ^ (key >> 16)) & 0xFFFF
    R, S, I = MPBB_R, MPBB_S, MPBB_I
    out = bytearray(len(data))
    for i, b in enumerate(data):
        b = (b + (w & 0xFF)) & 0xFF
        b = R[b]
        b = (b + (w >> 8)) & 0xFF
        b = S[b]
        b = (b - (w >> 8)) & 0xFF
        b = I[b]
        b = (b - (w & 0xFF)) & 0xFF
        out[i] = b
        w = (w + 1) & 0xFFFF
    return bytes(out)


def decode_block(data: bytes, crypt_method: int, bid: int) -> bytes:
    """Decode an external data block's payload according to ``crypt_method``."""
    if crypt_method == NDB_CRYPT_NONE:
        return data
    if crypt_method == NDB_CRYPT_PERMUTE:
        return permute_decode(data)
    if crypt_method == NDB_CRYPT_CYCLIC:
        return cyclic_crypt(data, bid)
    raise ValueError("unsupported bCryptMethod 0x%02x" % crypt_method)


def encode_block(data: bytes, crypt_method: int, bid: int) -> bytes:
    """Encode a plaintext data block payload according to ``crypt_method``."""
    if crypt_method == NDB_CRYPT_NONE:
        return data
    if crypt_method == NDB_CRYPT_PERMUTE:
        return permute_encode(data)
    if crypt_method == NDB_CRYPT_CYCLIC:
        return cyclic_crypt(data, bid)
    raise ValueError("unsupported bCryptMethod 0x%02x" % crypt_method)
