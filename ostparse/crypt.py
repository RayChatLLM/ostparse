"""
NDB block encryption as defined in [MS-PST] section 5 ("Algorithms").

* NDB_CRYPT_PERMUTE (0x01): a fixed byte-substitution cipher.
* NDB_CRYPT_CYCLIC  (0x02): a position-dependent substitution keyed by the
  low 32 bits of the block's BID.

The three 256-byte tables below are the substitution tables that the
specification calls ``mpbbR``, ``mpbbS`` and ``mpbbI`` (``mpbbI`` is the
inverse of ``mpbbR``; ``mpbbS`` is an involution).  Both algorithms are their
own inverse once the right table is picked, which the helpers below do.

Everything here is pure Python; the hot paths use ``bytes.translate`` so the
permute cipher runs at memcpy-like speed and the cyclic cipher is amortised
with a 256-step translation-table cache.
"""

